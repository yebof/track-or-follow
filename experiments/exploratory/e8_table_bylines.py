#!/usr/bin/env python3
"""EXPLORATORY (not pre-registered): the byline and publication-time table of Section 4.2.

    .venv/bin/python experiments/exploratory/e8_table_bylines.py   # -> paper/tables/table3_bylines.tex

The cells are the exploratory macros written from results/exploratory/e6_publication_timing.json and
e8_timing_robustness.json (exploratory_numbers_r1/r2.tex) and two registered macros (\\exEfivePriceShare is
exploratory; \\hTwoSpearmanEmu registered); this script only lays them out, so the table follows the result files.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "experiments" / "report"))
import _xtab as XT  # noqa: E402

OUT = ROOT / "paper" / "tables" / "table3_bylines.tex"
ROWS = [
    ("Desk bylines", r"\exEeightDeskSharePct", r"\exEeightDeskPricePct", r"\exEeightDesk", r"\exEeightDeskPub"),
    ("Named contributors", r"\exEeightNamedSharePct", r"\exEeightNamedPricePct", r"\exEeightNamed", r"\exEeightNamedPub"),
    None,
    ("Before the open, event day", r"\exEsixSharePreOpen", "---", r"\exEsixPreOpen", r"\exEsixPreOpenPub"),
    ("During the session", r"\exEsixShareIntraday", "---", r"\exEsixIntraday", r"\exEsixIntradayPub"),
    ("After the close or off-session", r"\exEsixShareAfter", "---", r"\exEsixAfter", r"\exEsixAfterPub"),
    None,
    ("All frame items", "100", r"\exEfivePriceShare", r"\hTwoSpearmanEmu", r"\exEsixPubAll"),
]


def main() -> int:
    lines = ["% GENERATED by experiments/exploratory/e8_table_bylines.py (exploratory (not pre-registered)) -- do not "
             "edit by hand (CLAUDE.md rule 2).",
             "{\\scriptsize\\setlength{\\tabcolsep}{4pt}", XT.begin("\\linewidth", "lrrrr"), "\\toprule",
             "& Share & Reports & $\\rho$ with & $\\rho$ from \\\\",
             "Items & (\\%) & move (\\%) & \\ARzo{} & publication \\\\", "\\midrule"]
    for r in ROWS:
        lines.append("\\midrule" if r is None else " & ".join(c if c.startswith("\\") is False else c + "{}"
                                                               for c in r) + " \\\\")
    lines += ["\\bottomrule", XT.END + "}"]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"table3_bylines -> {OUT.relative_to(ROOT)} (exploratory (not pre-registered))")
    return 0


if __name__ == "__main__":
    sys.exit(main())
