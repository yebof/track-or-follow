#!/usr/bin/env python3
"""EXPLORATORY v2 (post hoc; not pre-registered): the \\exVtwo macros for the rebuilt book (addendum v2.1, chosen on
W_hist) and the event-driven news overlay -> paper/generated/exploratory_numbers_v2.tex.

    .venv/bin/python experiments/v2/v2_make_numbers.py [--check]

Inputs: results/v2/v2_select.json, results/v2/v2_event_W_clean.json (each must carry the v2 exploratory label).
`main.tex` inputs this file after the other exploratory macro files; it never redefines a name they define. Every macro
comment carries the label "exploratory (not pre-registered)"; a sentence that uses one says "exploratory" in the same
sentence (outline_v2 §5.5). A missing input leaves a bold [name] placeholder and exit 1.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "experiments" / "report"))
sys.path.insert(0, str(ROOT / "experiments" / "exploratory"))
import _validity as V  # noqa: E402
from r1_make_numbers import c, n  # noqa: E402  (same formatting as the other exploratory macros)

OUT = ROOT / "paper" / "generated" / "exploratory_numbers_v2.tex"
LABEL = V.LABEL_X
V2_LABEL = "EXPLORATORY v2 (post hoc; not pre-registered)"
SSEL = "results/v2/v2_select.json"
SEV = "results/v2/v2_event_W_clean.json"


def load(rel: str) -> dict | None:
    p = ROOT / rel
    if not p.is_file():
        return None
    d = json.loads(p.read_text())
    if d.get("label") != V2_LABEL:
        raise SystemExit(f"{rel}: not a v2 exploratory output")
    return d


def macros_book(s: dict | None) -> list:
    m: list = []
    t = (s or {}).get("table") or {}
    for win, tag in (("W_hist", "Hist"), ("W_pre_slice", "Pre"), ("W_clean", "Clean")):
        b, ew = (t.get(win) or {}).get("chosen") or {}, (t.get(win) or {}).get("EW-U100") or {}
        src = f"{SSEL} table.{win}"
        m.append((f"exVtwoSharpe{tag}", n(V.get(b, "sharpe", "sharpe"), 2), f"rebuilt book Sharpe on {win}", src))
        m.append((f"exVtwoSharpe{tag}CI", c(V.get(b, "sharpe", "ci"), 2), f"95% interval of exVtwoSharpe{tag}", src))
        m.append((f"exVtwoSharpeEW{tag}", n(V.get(ew, "sharpe", "sharpe"), 2), f"EW-U100 Sharpe on {win}", src))
        m.append((f"exVtwoActive{tag}", n(b.get("active_ann"), 1, 100, sign=True),
                  f"rebuilt book minus EW-U100, % per year, {win}", src))
    cl = (t.get("W_clean") or {})
    m.append(("exVtwoMaxDDClean", n(V.get(cl, "chosen", "max_dd"), 1, 100), "rebuilt book max drawdown %, W_clean",
              f"{SSEL} table.W_clean.chosen.max_dd"))
    m.append(("exVtwoMaxDDEWClean", n(V.get(cl, "EW-U100", "max_dd"), 1, 100), "EW-U100 max drawdown %, W_clean",
              f"{SSEL} table.W_clean.EW-U100.max_dd"))
    m.append(("exVtwoTurnover", n(V.get(cl, "chosen", "turnover_per_year"), 1), "rebuilt book turnover per year, W_clean",
              f"{SSEL} table.W_clean.chosen.turnover_per_year"))
    rf = (s or {}).get("risk_filter") or {}
    m.append(("exVtwoFilterRelease", n(rf.get("active_vs_book_W_release"), 1, 100, sign=True), "negative-news risk "
              "filter minus the book, % per year, W_release (dropped by its rule)", f"{SSEL} risk_filter"))
    return m


def macros_event(e: dict | None) -> list:
    m: list = []
    rows = (e or {}).get("rows") or {}
    act = [V.get(r, "vs_base", "active_ann") for r in rows.values()]
    to = [V.get(r, "full", "turnover_per_year") for r in rows.values()]
    ok = rows and all(isinstance(x, float) for x in act + to)
    m.append(("exVtwoOverlayN", str(len(rows)) if rows else None, "event-overlay variants", f"{SEV} rows"))
    m.append(("exVtwoOverlayWorst", n(min(act), 1, 100) if ok else None, "overlay minus its base, % per year, worst",
              f"{SEV} rows.*.vs_base.active_ann"))
    m.append(("exVtwoOverlayBest", n(max(act), 1, 100) if ok else None, "overlay minus its base, % per year, best",
              f"{SEV} rows.*.vs_base.active_ann"))
    m.append(("exVtwoOverlayTurnLo", n(min(to), 0) if ok else None, "overlay turnover per year, lowest",
              f"{SEV} rows.*.full.turnover_per_year"))
    m.append(("exVtwoOverlayTurnHi", n(max(to), 0) if ok else None, "overlay turnover per year, highest",
              f"{SEV} rows.*.full.turnover_per_year"))
    return m


def render() -> tuple[str, list[str]]:
    rows = macros_book(load(SSEL)) + macros_event(load(SEV))
    lines = ["% paper/generated/exploratory_numbers_v2.tex -- GENERATED by experiments/v2/v2_make_numbers.py.",
             f"% Every macro below is {LABEL}: never a confirmatory or registered number. Do not edit by hand.",
             "\\providecommand{\\NumPlaceholder}[1]{\\textbf{[#1]}}"]
    missing = []
    for name, v, desc, src in rows:
        if v is None:
            missing.append(name)
            v = f"\\NumPlaceholder{{{name}}}"
        lines += [f"% {LABEL} | {desc} | {src}", f"\\newcommand{{\\{name}}}{{{v}}}"]
    return "\n".join(lines) + "\n", missing


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text, missing = render()
    if a.check:
        stale = not OUT.is_file() or OUT.read_text() != text
        print("exploratory_numbers_v2: " + ("stale" if stale else "up to date") +
              (f"; missing: {', '.join(missing)}" if missing else ""))
        return 1 if stale or missing else 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}" + (f"; MISSING (placeholders): {', '.join(missing)}" if missing else ""))
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
