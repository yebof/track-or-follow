"""LaTeX table bodies for the paper's tables (outline_v1 §4 "Tables"): booktabs, no vertical rules, numbers
right-aligned with a fixed number of decimals per column, CIs in brackets, "—" = not run, "n/a" = not applicable,
no bolding of best values. Each table script writes only the tabular environment; the caption and label stay in
paper/sections/*.tex.

Every table script reads results/analysis/<name>.json files. A file of a non-registered window (a development run)
is refused for paper/tables/ and must be written elsewhere with --out-dir (`check_inputs`).
"""

from __future__ import annotations

import json
import math
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TABLE_DIR = ROOT / "paper" / "tables"
ANALYSIS = ROOT / "results" / "analysis"
NOT_RUN, NA = "---", "n/a"
MINUS = "\\ensuremath{-}"


def finite(x) -> bool:
    return isinstance(x, (int, float)) and not isinstance(x, bool) and math.isfinite(x)


def num(x, d: int = 2, scale: float = 1.0, sign: bool = False) -> str:
    """A number with `d` decimals (math minus); '---' when missing."""
    if not finite(x):
        return NOT_RUN
    v = float(x) * scale
    s = f"{abs(v):,.{d}f}".replace(",", "{,}")
    if v < 0 and float(s.replace("{,}", "")) != 0:
        return MINUS + s
    return ("+" + s) if sign and v > 0 else s


def ci(lo, hi, d: int = 2, scale: float = 1.0) -> str:
    if not (finite(lo) and finite(hi)):
        return ""
    return f"[{num(lo, d, scale)}, {num(hi, d, scale)}]"


def est_ci(est, interval, d: int = 2, scale: float = 1.0, sep: str = " ") -> str:
    if not finite(est):
        return NOT_RUN
    lo, hi = (interval or [None, None])[:2] if interval is not None else (None, None)
    c = ci(lo, hi, d, scale)
    return num(est, d, scale) + (sep + "{\\tiny " + c + "}" if c else "")


def pct(x, d: int = 1) -> str:
    return num(x, d, 100.0)


def get(d: Mapping | None, *path, default=None):
    for k in path:
        if not isinstance(d, Mapping) or k not in d:
            return default
        d = d[k]
    return d


def load(name: str, in_dir: Path | None = None) -> dict | None:
    p = (Path(in_dir) if in_dir else ANALYSIS) / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else None


def check_inputs(docs: Sequence[dict | None], out_dir: Path | None) -> Path:
    """Refuse to write a development run into paper/tables/: every loaded file must be of the registered window unless
    an explicit output directory is given."""
    if out_dir is not None:
        return Path(out_dir)
    for d in docs:
        if d is not None and not get(d, "meta", "registered_window", default=False):
            sys.exit(f"refused: {get(d, 'meta', 'script')} output is for window {get(d, 'meta', 'window')}, not the "
                     "registered one; pass --out-dir to write a development table elsewhere")
    return TABLE_DIR


def tabular(colspec: str, header: Sequence[str] | str, body: Sequence[str], note: str | None = None,
            size: str = "\\footnotesize") -> str:
    head = header if isinstance(header, str) else " & ".join(header) + " \\\\"
    lines = ["% GENERATED by experiments/report/ -- do not edit by hand (CLAUDE.md rule 2).", "{" + size,
             "\\setlength{\\tabcolsep}{3pt}", f"\\begin{{tabular}}{{{colspec}}}", "\\toprule", head, "\\midrule",
             *body, "\\bottomrule", "\\end{tabular}"]
    if note:
        lines.append("\\par\\smallskip{\\scriptsize " + note + "}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def row(*cells) -> str:
    return " & ".join(str(c) for c in cells) + " \\\\"


def write(out_dir: Path, name: str, text: str) -> Path:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    p = out_dir / f"{name}.tex"
    p.write_text(text)
    return p


def tex_escape(s: str) -> str:
    return (str(s).replace("\\", "\\textbackslash{}").replace("&", "\\&").replace("%", "\\%").replace("_", "\\_")
            .replace("#", "\\#").replace("$", "\\$"))
