#!/usr/bin/env python3
"""Table 4: the compact portfolio table (PD1; outline_v1 §3 Table 4; design_v2_delta PE-16).

    .venv/bin/python experiments/report/table4_portfolio.py          # results/analysis/pd1.json -> paper/tables/
    .venv/bin/python experiments/report/table4_portfolio.py --in-dir results/analysis/W_pre_slice --out-dir X

Rows in the registered order (system book, signal book, EW-U100, SPY, vol-managed EW-U100, momentum 12-1, LightGBM on
the code features, code-only system). Columns: annualized excess return over cash (%), volatility (%), Sharpe with its
studentized block-bootstrap 95% interval, maximum drawdown (%), one-way turnover per rebalance (%), break-even cost
against EW-U100 (bps per side; "---" for EW-U100 itself; +inf/-inf printed as such), own-factor selection alpha (%,
annualized) with its NW 95% interval. The DSR, the number of registered trials and the Random-20 percentile are
caption macros (make_numbers: nTrials, dsr, randomPct). Estimates, not tests.
"""

from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _latex as L

NAME = "table4_portfolio"


def breakeven(x) -> str:
    if x in ("+inf", "-inf"):
        return "$+\\infty$" if x == "+inf" else "$-\\infty$"
    if isinstance(x, (int, float)) and math.isinf(x):
        return "$+\\infty$" if x > 0 else "$-\\infty$"
    return L.num(x, 0)


LABELS = {"sized": "System book", "sel_ew": "Signal book (equal weight)", "ew_u100": "Equal-weight universe",
          "spy": "S\\&P 500 ETF", "vm_ew_u100": "Vol-managed equal weight"}  # round-1 editor review T5: no run tags


def build(d: dict) -> str:
    """One line of estimates per book and, under it, the Sharpe and alpha intervals (the table sits in one column)."""
    body = []
    for k in d["order"]:
        r = dict(d["rows"][k])
        r["label"] = LABELS.get(k, r["label"])
        sh = r.get("sharpe") or {}
        al = r.get("alpha") or {}
        a_ci = L.ci(*(al.get("ci") or [None, None])[:2], 1, 100.0)
        body.append(L.row(r["label"], L.pct(r.get("ann_excess_return"), 1), L.pct(r.get("ann_vol"), 1),
                          L.num(sh.get("sharpe"), 2), L.pct(r.get("max_drawdown"), 1),
                          L.pct(r.get("turnover_one_way"), 1),
                          L.NOT_RUN if k == "ew_u100" else breakeven(r.get("break_even_bps_vs_ew")),
                          L.num(al.get("annualized"), 1, 100.0) + (" " + a_ci if a_ci else "")))
    header = "& Ex.\\ ret. & Vol. & Sharpe & MDD & TO & BE & $\\alpha$ \\\\"
    note = ("Ex.\\ ret.: annualized excess return (\\%); Vol.: volatility (\\%); MDD: maximum drawdown (\\%); TO: "
            "one-way turnover per rebalance (\\%); BE: break-even cost against equal weight (bps per side; "
            "$-\\infty$: none); $\\alpha$: own-factor selection alpha (\\%/yr).")
    t = L.tabular("lrrrrrrr", header, body, None, size="\\scriptsize").replace(
        "\\setlength{\\tabcolsep}{3pt}", "\\setlength{\\tabcolsep}{2pt}").replace(
        "% GENERATED by experiments/report/ --", "% GENERATED by experiments/report/table4_portfolio.py --")
    return t.rstrip().removesuffix("}") + ("\\par\\smallskip\n\\begin{minipage}{\\linewidth}\\scriptsize"
                                           "\\raggedright\n" + note + "\n\\end{minipage}\n}\n")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--in-dir", default=None)
    ap.add_argument("--out-dir", default=None)
    a = ap.parse_args(argv)
    d = L.load("pd1", a.in_dir)
    if d is None:
        sys.exit("table4: pd1.json missing (run experiments/analysis/pd1_portfolio.py)")
    out = L.check_inputs([d], a.out_dir)
    p = L.write(out, NAME, build(d))
    print(f"table4 -> {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
