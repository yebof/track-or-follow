#!/usr/bin/env python3
"""Table 4 of the validity-first paper: what validity bought at the decision horizon, and cost (outline_v2 §3
"Table 4"; DEV-12). The compact portfolio and operating profile; the full registered tables stay in App. G.

    .venv/bin/python experiments/report/table4_horizon_ops.py     # -> paper/tables/table4_horizon_ops.tex

Panel A, signal (the learned weeks of H3): H3's rank-IC increment of the system's pooled logit over its code-only twin
(C) with its two-sided 95% interval, its registered split (text part; trusted typed part), the W_release sensitivity,
and the value of the text to the signal book (J = infinity minus J = 0, bps per week). Panel B, portfolio (registered
PD1 estimates, net of the registered cost per side; no test): system book, signal book, EW-U100, SPY and the code-only
system with Sharpe [95% interval], annualized excess return, maximum drawdown and one-way turnover. Panel C, cost of
the confirmatory reader at the pinned model's list price: $ per weekly rebalance, $ per news item, p95 latency,
wall-clock of the reading layer over all weeks; the open model's CPU seconds per item.

Inputs (registered, lock open; refused otherwise): results/analysis/h3.json, frontier.json, pd1.json, pd0.json;
results/prereg/power_prereg.json. Writes only the tabular; caption and label live in paper/sections/.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _latex as L  # noqa: E402  (registered formatting helpers, read-only)
import _xtab as XT  # noqa: E402  (tabularx for alternating row colours)
import _validity as V  # noqa: E402

NAME = "table4_horizon_ops"
ROOT = V.ROOT
POWER = ROOT / "results/prereg/power_prereg.json"
BOOKS = ("sized", "sel_ew", "ew_u100", "spy", "codeonly")


LABELS = {"sized": "System book", "sel_ew": "Signal book", "ew_u100": "Equal-weight universe",
          "spy": "S\\&P 500 ETF", "codeonly": "Code-only system"}  # editor review T5: no run tags


def e(x, d=3, scale=1.0) -> str:
    return L.num(x, d, scale) if L.finite(x) else L.NOT_RUN


def c_(v, d=3, scale=1.0) -> str:
    return L.ci(*(v or [None, None])[:2], d, scale) or L.NOT_RUN


def tab(colspec: str, rows: list[str]) -> list[str]:
    return [XT.begin("\\linewidth", colspec), "\\toprule", *rows, "\\bottomrule", XT.END]


def build(h3: dict, fr: dict, pd1: dict, pd0: dict) -> str:
    """Two tabulars with their own headers (round-2 figure review T3-1) and a leading status column (T3-2); estimates
    and intervals in separate columns at one type size."""
    c = h3["confirmatory"]
    sp = h3["split"]
    rel = h3["sensitivities"]["W_release"]
    ic = h3.get("ic") or {}
    v = fr["value_of_text"]
    tp, tt = sp["text_part_IC_L_minus_IC_LT"], sp["trusted_typed_part_IC_LT_minus_IC_codeonly"]
    a = ["\\multicolumn{4}{l}{\\textit{Rank information at the decision horizon, %d learned weeks}} \\\\"
         % c["n_weeks"], "\\midrule", "& Measure & Est. & 95\\% CI \\\\", "\\midrule",
         L.row("C", "H3: $\\Delta$IC over the code-only twin", e(c["mean"]), c_(c["ci"])),
         L.row("R", "\\quad text part", e(tp["mean"]), c_(tp["ci"])),
         L.row("R", "\\quad trusted typed part", e(tt["mean"]), c_(tt["ci"])),
         L.row("R", f"\\quad after release, {rel['n_weeks']} weeks", e(rel["mean"]), c_(rel["ci"])),
         L.row("R", "IC of the full system", e(V.get(ic, "primary", "mean")), c_(V.get(ic, "primary", "ci"))),
         L.row("R", "IC of the code-only twin", e(V.get(ic, "codeonly", "mean")), c_(V.get(ic, "codeonly", "ci")))]
    # the portfolio panel and the value of the text moved to App. E (user, 2026-10-22: portfolio results in the appendix)
    note = ("C: confirmatory (one-sided, Holm over H1--H3); R: registered estimate, 95\\% interval. IC: weekly "
            "Spearman correlation of the combined logit with the holding week's relative return.")
    lines = ["% GENERATED by experiments/report/table4_horizon_ops.py -- do not edit by hand (CLAUDE.md rule 2).",
             "{\\footnotesize", "\\setlength{\\tabcolsep}{5pt}", *tab("clrl", a), "\\par\\smallskip",
             "\\begin{minipage}{\\linewidth}\\scriptsize\\raggedright", note, "\\end{minipage}", "}"]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    docs = [V.require_registered(n) for n in ("h3", "frontier", "pd1", "pd0")]
    p = L.write(L.TABLE_DIR, NAME, build(*docs))
    print(f"table4_horizon_ops -> {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
