#!/usr/bin/env python3
"""App. F box: one per-item typed request of the news agent, quoted from the frozen question bank.

    .venv/bin/python experiments/report/box_typed_request.py   # -> paper/tables/boxA_typed_request.tex

Every string is copied from docs/design/question_bank_v1.json (the system prompt of the confirmatory reader, the state
schema of the per-item stage, and four of its questions); score levels are shown by their names (the text before the
first colon). Nothing here is paraphrased.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BANK = ROOT / "docs" / "design" / "question_bank_v1.json"
OUT = ROOT / "paper" / "tables" / "boxA_typed_request.tex"
SHOWN = ("new_development", "instructs_reader", "promotional", "effect")


def tex(s: str) -> str:
    s = s.replace("\\", "\\textbackslash{}")
    for a, b in (("&", "\\&"), ("%", "\\%"), ("$", "\\$"), ("#", "\\#"), ("_", "\\_"), ("{", "\\{"), ("}", "\\}")):
        s = s.replace(a, b)
    s = s.replace("\\textbackslash\\{\\}", "\\textbackslash{}")
    return re.sub(r"`([^`]+)`", r"\\texttt{\1}", s)


def main() -> int:
    b = json.loads(BANK.read_text(encoding="utf-8"))
    n1, conv = b["programs"]["N1"], b["conventions"]
    schema = b["state_schemas"]["N1"]
    lines = ["% GENERATED by experiments/report/box_typed_request.py from docs/design/question_bank_v1.json -- do not "
             "edit by hand (CLAUDE.md rule 2).",
             "{\\scriptsize\\setlength{\\fboxsep}{3pt}\\setlength{\\fboxrule}{0.4pt}%",
             "\\noindent\\fcolorbox{black!35}{black!4}{\\begin{minipage}{\\dimexpr\\linewidth-2\\fboxsep-2\\fboxrule"
             "\\relax}\\raggedright",
             "\\textbf{State} (JSON built in code). \\texttt{note}: \\emph{" + tex(conv["note_text"]) + "} "
             "Further fields: " + ", ".join(f"\\texttt{{{tex(k)}}}" for k in schema if k != "note")
             + " (pseudonym, industry and size bucket; headline, screened summary sentences, source, relative "
             "publication time and tagged firms).\\par",
             "\\smallskip\\textbf{Questions} (four of " + str(len(n1)) + ", asked in one request).\\par"]
    for q in SHOWN:
        d = n1[q]
        ins = d["instructions"]
        if isinstance(ins, dict):
            ins = " ".join(ins.values())
        if d["kind"] == "noul":
            opts = f"yes: {tex(d['true'])} no: {tex(d['false'])}"
        else:
            opts = "levels: " + "; ".join(tex(x.split(":", 1)[0]) for x in d["levels"])
        lines.append(f"\\hangindent=1em\\texttt{{{tex(q)}}}. {tex(ins)} \\emph{{{opts}}}\\par")
    lines += ["\\end{minipage}}%", "}"]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"boxA_typed_request -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
